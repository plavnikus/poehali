def replace_field(line, field, value):
    pat = re.compile(r'(' + re.escape(field) + r':)([\'\"])(.*?)(\2)(?=,|})')
    m=pat.search(line)
    if not m:
        raise RuntimeError(f'field {field} not found')
    quote=m.group(2)
    if quote in value:
        raise RuntimeError(f'quote collision for {field}')
    return line[:m.start()] + m.group(1) + quote + value + quote + line[m.end():]

def patch_details():
    p=Path('details.js'); lines=p.read_text(encoding='utf-8').splitlines()
    seen=set()
    out=[]
    for line in lines:
        m=re.search(r"PLACE_DETAILS\['([^']+)'\]", line)
        if m and m.group(1) in DETAIL_UPDATES:
            pid=m.group(1); seen.add(pid)
            for field,value in DETAIL_UPDATES[pid].items():
                line=replace_field(line,field,value)
            for old,new in FACT_REPLACES.get(pid,[]):
                if line.count(old)!=1: raise RuntimeError(f'fact text not found {pid}')
                line=line.replace(old,new,1)
        out.append(line)
    missing=set(DETAIL_UPDATES)-seen
    if missing: raise RuntimeError('missing detail ids '+str(missing))
    p.write_text('\n'.join(out)+'\n',encoding='utf-8')

def patch_json_file(path,prefix,suffix,updates):
    p=Path(path); s=p.read_text(encoding='utf-8').strip()
    if not (s.startswith(prefix) and s.endswith(suffix)): raise RuntimeError('wrapper mismatch '+path)
    raw=s[len(prefix):-len(suffix)]
    arr=json.loads(raw)
    byid={x['i']:x for x in arr}
    for pid,vals in updates.items():
        if pid not in byid: raise RuntimeError(f'{pid} missing in {path}')
        for k,v in vals.items(): byid[pid][k]=v
    p.write_text(prefix+json.dumps(arr,ensure_ascii=False,separators=(',',':'))+suffix+'\n',encoding='utf-8')

